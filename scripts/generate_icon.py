#!/usr/bin/env python3
"""Draws the app icon, a 3x3 LED panel after the OBEGRÄNSAD front, and writes
include/app_icon.h with the PNGs the web server hands out (home screen, favicon).

  python3 scripts/generate_icon.py [preview-folder]   (needs Pillow)
"""

import io
import os
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

BACKGROUND = (14, 14, 16)
LED_OFF = (34, 34, 38)
LED_ON = (255, 244, 224)  # warm white, like the lamp's LEDs
# lit pattern, row by row: 1 on, 0 off
PATTERN = ["111", "101", "111"]

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "include", "app_icon.h")


def draw_icon(size):
    scale = 4  # draw large, then shrink for smooth edges
    big = size * scale
    image = Image.new("RGB", (big, big), BACKGROUND)

    margin = big * 0.2
    cell = (big - 2 * margin) / 3
    radius = cell * 0.3

    def circle(draw, row, column, r, colour):
        cx = margin + cell * (column + 0.5)
        cy = margin + cell * (row + 0.5)
        draw.ellipse((cx - r, cy - r, cx + r, cy + r), fill=colour)

    # soft glow around the lit LEDs
    glow = Image.new("RGB", (big, big), (0, 0, 0))
    glow_draw = ImageDraw.Draw(glow)
    for row in range(3):
        for column in range(3):
            if PATTERN[row][column] == "1":
                circle(glow_draw, row, column, radius * 1.5, (120, 104, 80))
    glow = glow.filter(ImageFilter.GaussianBlur(radius * 0.9))
    image = ImageChops.add(image, glow)

    draw = ImageDraw.Draw(image)
    for row in range(3):
        for column in range(3):
            lit = PATTERN[row][column] == "1"
            circle(draw, row, column, radius, LED_ON if lit else LED_OFF)

    return image.resize((size, size), Image.LANCZOS)


def png_bytes(image):
    buffer = io.BytesIO()
    image.save(buffer, "PNG", optimize=True)
    return buffer.getvalue()


def c_array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    touch = draw_icon(180)
    favicon = draw_icon(64)
    if len(sys.argv) > 1:
        touch.save(os.path.join(sys.argv[1], "icon-180.png"))
        draw_icon(512).save(os.path.join(sys.argv[1], "icon-512.png"))

    with open(OUTPUT, "w") as f:
        f.write(
            "#pragma once\n\n"
            "// Generated by scripts/generate_icon.py, do not edit.\n"
            "// App icon: a 3x3 LED panel, served for the home screen and as favicon.\n\n"
            "#include <Arduino.h>\n\n"
            + c_array("APP_ICON_180", png_bytes(touch))
            + "\n\n"
            + c_array("APP_ICON_64", png_bytes(favicon))
            + "\n"
        )
    print(f"wrote {os.path.normpath(OUTPUT)}")


if __name__ == "__main__":
    main()
